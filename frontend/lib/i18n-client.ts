export function localeRoleClass(
  locale: PublicLocale,
  role: keyof typeof localeRoleClasses.en,
): string {
  return localeRoleClasses[locale][role]
}

export function localePageClass(locale: PublicLocale): string {
  return locale === 'hi' ? 'public-locale-hi' : ''
}

export function localePlaceName(value: string | undefined, locale: PublicLocale): string {
  if (!value || locale === 'en') return value ?? ''
  const places: Record<string, string> = {
    patna: 'पटना',
    bihar: 'बिहार',
    'boring road': 'बोरिंग रोड',
    patliputra: 'पाटलिपुत्र',
    kankarbagh: 'कंकड़बाग',
    danapur: 'दानापुर',
  }
  return places[value.trim().toLowerCase()] ?? value
}

